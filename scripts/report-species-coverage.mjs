#!/usr/bin/env node
/**
 * The species surface coverage report, generated — never typed.
 *
 *   node scripts/report-species-coverage.mjs           # write docs/species-spatial-coverage.md
 *   node scripts/report-species-coverage.mjs --check   # exit 1 if the committed report is stale
 *   node scripts/report-species-coverage.mjs --json    # the same rows as JSON, for scripts
 *
 * Every row is `spatialStrategyFor` over the certified registries and what the
 * species-surface endpoint actually serves, and "renderable" is the one
 * renderer's own conversion run on that reply. A browser-verified stage is only
 * what the verification record holds for the artifact's CURRENT hash. So the
 * report cannot say a species has a map unless a hunter could receive one.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { permitsHuntingOpportunity } from "../src/lib/content/species-eligibility.ts";
import { toRenderable } from "../src/lib/hunt/exploration/surface-request.ts";
import { spatialStrategies, COVERAGE_STAGES } from "../src/lib/hunt/intelligence/spatial-strategy.ts";
import { speciesSurfaces, SURFACE_TIERS, TIER_MEANING } from "../src/lib/hunt/intelligence/surface.ts";

const OUT = join(process.cwd(), "docs", "species-spatial-coverage.md");

const TIER_WORDS = {
  MEASURED_DENSITY: "T1 measured density",
  MODELLED_ABUNDANCE: "T2 modelled abundance",
  SYSTEMATIC_SURVEY: "T3 systematic survey",
  HABITAT_MODEL: "T4 habitat model",
  RANGE_HABITAT: "T5 range + habitat",
  RANGE_ONLY: "T6 known distribution",
  NO_SURFACE: "no surface",
};

const rows = spatialStrategies().map((row) => {
  const eligible = permitsHuntingOpportunity(row.speciesId);
  const reply = row.tier === "NO_SURFACE" ? null : speciesSurfaces(row.speciesId);
  const renderable = reply ? reply.surfaces.filter((surface) => toRenderable(surface)).length : 0;
  const served = row.layers.filter((layer) => layer.served);
  const box = served.map((layer) => layer.geography).filter(Boolean).reduce((acc, g) => (acc
    ? { west: Math.min(acc.west, g.west), south: Math.min(acc.south, g.south), east: Math.max(acc.east, g.east), north: Math.max(acc.north, g.north) }
    : g), null);
  return {
    ...row,
    eligible,
    renderable,
    productionReachable: row.layers.some((layer) => layer.stage === "PRODUCTION_VERIFIED"),
    evidence: row.tier === "NO_SURFACE" ? "—" : TIER_MEANING[row.tier].represents,
    geography: box ? `${box.south.toFixed(1)}–${box.north.toFixed(1)}°N, ${(-box.east).toFixed(1)}–${(-box.west).toFixed(1)}°W` : row.plotJurisdictions.length ? `plots in ${row.plotJurisdictions.map((j) => j.replace("jurisdiction:ca-", "").toUpperCase()).join(", ")}` : "—",
  };
});

const eligible = rows.filter((row) => row.eligible);
const withSurface = eligible.filter((row) => row.tier !== "NO_SURFACE");
const byTier = [...SURFACE_TIERS, "NO_SURFACE"].map((tier) => `${TIER_WORDS[tier]}: ${eligible.filter((row) => row.tier === tier).length}`);
const byStage = COVERAGE_STAGES.map((stage) => `${stage}: ${eligible.filter((row) => row.stage === stage).length}`);
const production = eligible.filter((row) => row.productionReachable).length;
const blocked = eligible.filter((row) => row.tier === "NO_SURFACE");
const pct = (n) => `${((100 * n) / Math.max(1, eligible.length)).toFixed(1)}%`;

if (process.argv.includes("--json")) {
  process.stdout.write(`${JSON.stringify({ eligible: eligible.length, withSurface: withSurface.length, productionReachable: production, rows }, null, 1)}\n`);
  process.exit(0);
}

const cell = (value) => String(value).replace(/\|/g, "\\|");
const lines = [
  "# Species surface coverage",
  "",
  "Generated by `scripts/report-species-coverage.mjs` from the certified registries",
  "(`content/intelligence/surface-registry.json`, `model-registry.json`, `range-habitat-registry.json`,",
  "the servable evidence bundles), what the species-surface endpoint serves, and the one renderer's",
  "own conversion. Do not edit by hand; `npm test` fails when this file is stale.",
  "",
  "CLAUDE.md §41B: every Hunt-eligible species resolves to the strongest surface its evidence",
  "defensibly supports. A **surface** is what the map paints; **zone evidence** is one figure per",
  "management unit, shown in that unit's card and never painted. NO_SURFACE stands only on a genuine",
  "blocker (not Hunt-eligible, no defensible range, licence forbids); anything else fails the gate.",
  "",
  `**${eligible.length} Hunt-eligible species** (of ${rows.length} published). **${withSurface.length} with a served, renderable surface (${pct(withSurface.length)}); ${blocked.length} without.** Production-verified in a real browser: ${production} (${pct(production)}).`,
  "",
  `**By tier:** ${byTier.join(" · ")}.`,
  "",
  `**Map-layer stage:** ${byStage.join(" · ")}.`,
  "",
  "| Species | Eligibility | Best tier | Surfaces (artifact · confidence) | Certified | Served | Renderable | Production | Evidence | Coverage geography | Zone evidence (card only) | Blocker |",
  "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map((row) => {
    const surfaces = row.layers.map((layer) => `${layer.artifactId.replace("surface:", "")} · ${layer.confidence.toLowerCase()}`).join("; ") || (row.plotJurisdictions.length ? "survey plots" : "—");
    const certified = row.layers.length || row.plotJurisdictions.length ? "yes" : "—";
    const served = row.layers.some((layer) => layer.served) || row.plotJurisdictions.length ? "yes" : "—";
    return `| ${row.speciesId.replace("species:", "")} | ${row.eligibility ?? "—"} | ${TIER_WORDS[row.tier]} | ${cell(surfaces)} | ${certified} | ${served} | ${row.renderable ? "yes" : "—"} | ${row.productionReachable ? "yes" : "—"} | ${cell(row.evidence)} | ${row.geography} | ${row.zoneEvidenceJurisdictions.map((j) => j.replace("jurisdiction:ca-", "").toUpperCase()).join(", ") || "—"} | ${row.blocker ? `${row.blocker.genuine ? "" : "**NOT GENUINE** "}${row.blocker.reason}: ${cell(row.blocker.detail)}` : "—"} |`;
  }),
  "",
];
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* reported below */ }
  if (current !== text) {
    process.stderr.write("docs/species-spatial-coverage.md is stale. Run node scripts/report-species-coverage.mjs\n");
    process.exit(1);
  }
  process.stdout.write(`species coverage report current: ${withSurface.length}/${eligible.length} eligible species with a surface\n`);
} else {
  writeFileSync(OUT, text);
  process.stdout.write(`Wrote ${OUT}: ${withSurface.length}/${eligible.length} eligible species with a surface; ${production} production-verified\n`);
}
