#!/usr/bin/env node
/**
 * The species spatial-coverage matrix, generated — never typed.
 *
 *   node scripts/report-species-coverage.mjs           # write docs/species-spatial-coverage.md
 *   node scripts/report-species-coverage.mjs --check   # exit 1 if the committed matrix is stale
 *
 * Every row is `spatialStrategyFor` over the certified registries and the
 * declared plans, so the matrix cannot say a species is covered unless the
 * registries do, and a browser-verified stage is only what the verification
 * record holds for the artifact's CURRENT hash.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { spatialStrategies, COVERAGE_STAGES } from "../src/lib/hunt/intelligence/spatial-strategy.ts";

const OUT = join(process.cwd(), "docs", "species-spatial-coverage.md");

const STRATEGY_WORDS = {
  A_MEASURED_DENSITY: "A — measured density",
  B_MEASURED_DISTRIBUTION: "B — measured distribution",
  C_HABITAT_MODEL: "C — habitat model",
  D_COARSE_SUPPORTING: "D — zone evidence (not painted)",
  E_NO_DEFENSIBLE_SURFACE: "E — nothing defensible yet",
};

const short = (id) => id.replace("jurisdiction:ca-", "").replace("jurisdiction:us-", "us-").toUpperCase();

const rows = spatialStrategies();
const count = (predicate) => rows.filter(predicate).length;
const byStrategy = Object.keys(STRATEGY_WORDS).map((key) => `${STRATEGY_WORDS[key]}: ${count((row) => row.strategy === key)}`);
const byStage = COVERAGE_STAGES.map((stage) => `${stage}: ${count((row) => row.stage === stage)}`);

const lines = [
  "# Species spatial coverage",
  "",
  "Generated by `scripts/report-species-coverage.mjs` from the certified registries",
  "(`content/intelligence/surface-registry.json`, `model-registry.json`, `range-habitat-registry.json`,",
  "the servable evidence bundles) and the",
  "declared plans (`content/intelligence/spatial-strategy.json`). Do not edit by hand;",
  "`npm test` fails when this file is stale.",
  "",
  "A **surface** is what the map paints. **Zone evidence** is one figure per management",
  "unit, shown in that unit's card and never painted (§41B). A **plan** is never coverage.",
  "",
  `**${rows.length} species.** ${byStrategy.join(" · ")}.`,
  "",
  `**Map-layer stage:** ${byStage.join(" · ")}.`,
  "",
  "| Species | Family | Strategy held | Surface | Survey plots | Zone evidence | Stage | Next |",
  "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map((row) => {
    const surface = [
      row.raster ? `BBS field ${row.raster.methodologyVersion}, ${row.raster.colourScale === "RANK_AMONG_DETECTED" ? "rank" : "ratio"} scale, ${row.raster.seasonalMovement?.toLowerCase() ?? "migratory"}` : null,
      row.model ? `habitat model ${row.model.methodologyVersion}${row.raster ? " beyond it" : ""} (${row.model.stage.toLowerCase().replace(/_/g, " ")})` : null,
      row.records ? `recorded presence ${row.records.methodologyVersion} (${row.records.stage.toLowerCase().replace(/_/g, " ")})` : null,
    ].filter(Boolean).join("; ") || "—";
    const next = row.next.map((plan) => `${plan.strategy.slice(0, 1)} ${plan.status.toLowerCase().replace("_", " ")}`).join("; ") || "—";
    return `| ${row.speciesId.replace("species:", "")} | ${(row.family ?? "—").toLowerCase().replace(/_/g, " ")} | ${STRATEGY_WORDS[row.strategy]} | ${surface} | ${row.plotJurisdictions.map(short).join(", ") || "—"} | ${row.zoneEvidenceJurisdictions.map(short).join(", ") || "—"} | ${row.stage} | ${next} |`;
  }),
  "",
];
const text = `${lines.join("\n")}`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* reported below */ }
  if (current !== text) {
    process.stderr.write("docs/species-spatial-coverage.md is stale. Run node scripts/report-species-coverage.mjs\n");
    process.exit(1);
  }
  process.stdout.write(`species coverage matrix current: ${rows.length} species\n`);
} else {
  writeFileSync(OUT, text);
  process.stdout.write(`Wrote ${OUT}: ${rows.length} species\n`);
}
