/**
 * Make sure an AGENTS.md exists, so `next dev` does not append its managed
 * agent-rules block to CLAUDE.md.
 *
 * WHY THIS EXISTS. Next 16.3.5 ships `generate-agent-files.js`, which on
 * `next dev` writes a `<!-- BEGIN:nextjs-agent-rules -->` block into an agent
 * file. Its own order of preference decides which file:
 *
 *     if (agentsMdExists && (agentsMdHostsBlock || !claudeMdHostsBlock))
 *         -> write AGENTS.md, SKIP CLAUDE.md
 *     if (claudeMdExists)
 *         -> write CLAUDE.md          <- what happened here
 *
 * With no AGENTS.md it fell through to CLAUDE.md, which CLAUDE.md §65 reserves
 * for the owner — and the block's own text argues for committing it, so an
 * agent reading a dirty tree is being invited to commit a change to the
 * project's direction document. Creating any AGENTS.md takes the first branch
 * instead. Nothing here depends on a Next internal: the file merely has to
 * exist.
 *
 * It runs as `predev` because a worktree starts without AGENTS.md (it is
 * gitignored), and this project creates worktrees constantly. Without this,
 * the protection would hold only in whichever checkout someone fixed by hand.
 *
 * Starting a server some other way — `npx next dev` directly, as happens when
 * a lane needs its own port — skips `predev` and CLAUDE.md is exposed again.
 * That is the known gap; `git checkout CLAUDE.md` is the repair.
 */
import { existsSync, writeFileSync } from "node:fs";

const PATH = new URL("../AGENTS.md", import.meta.url);

/* Not overwritten if present: `next dev` upserts its block into this file, and
   rewriting it every run would undo that and churn the file. */
if (!existsSync(PATH)) {
  writeFileSync(PATH, `# North Ground — agent notes

North Ground's direction, product decisions and working rules are in CLAUDE.md;
read that file, not this one.

This file exists so that \`next dev\` writes its managed agent-rules block here
rather than appending it to CLAUDE.md, which CLAUDE.md §65 reserves for the
owner. It is gitignored and regenerated by \`scripts/ensure-agents-md.mjs\`.
`, "utf-8");
  console.log("Created AGENTS.md so next dev leaves CLAUDE.md alone.");
}
